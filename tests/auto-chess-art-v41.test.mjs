import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import ts from 'typescript';
import {decodeNative} from '../art-source/v39/autochess/items-and-fx/inspect-native.mjs';

let checks=0;
const ok=(value,message)=>{assert.ok(value,message);checks++;};
const eq=(value,expected,message)=>{assert.deepEqual(value,expected,message);checks++;};
const json=file=>JSON.parse(readFileSync(file,'utf8'));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
function compile(file){const exports={};new Function('require','exports',ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText)(id=>{throw Error('Unexpected runtime dependency '+id);},exports);return exports;}
const art=compile('lib/art/autoChessInterfaceArtV41.ts'),entries=art.AUTO_CHESS_INTERFACE_ART_V41;
const idle=compile('lib/art/autoChessIdleArtV41.ts').AUTO_CHESS_IDLE_ART_V41;
const catalog=compile('lib/game/autoChessCatalogV40.ts').CHESS_PIECES_V40;
const pieces={...compile('lib/art/autoChessArtV39.ts').AUTO_CHESS_PIECE_ART_V39,...compile('lib/art/autoChessArtV40.ts').AUTO_CHESS_PIECE_ART_V40};
const manifest=json('art-source/v41/autochess/ui/manifest.json'),measurements=json('art-source/v41/autochess/idle-crops.json');
const legacy=json('art-source/v39/autochess/manifest.json'),expansion=json('art-source/v40/autochess/manifest.json');
const pieceRecords=new Map([...legacy.pieces,...legacy.companions,...expansion.pieces].map(record=>[record.path,record]));

eq(manifest.complete,true,'official 3D UI registration is complete');
eq(manifest.renderStyle,'stylized-3d','latest requested UI material direction');
eq(manifest.pixelEditingPerformed,false,'native PNG pixels were never edited');
eq(manifest.nativeBytesPreserved,true,'registration preserves original generated bytes');
eq(manifest.svgViewportsOnly,true,'SVGs are measured native-image viewports');
eq(Object.keys(entries).sort(),['active','buttonActive','buttonQuiet','panel','shop'],'all five production UI frames exist');
eq(entries,manifest.entries,'runtime registry and final manifest agree');
eq(manifest.nativeSources.length,4,'four native 3D sources, including two button states');
ok(existsSync('art-source/v41/autochess/ui/2d-exploration/manifest.json'),'earlier flat-art exploration is archived');

for(const record of manifest.nativeSources){
 const label=record.id,file='public'+record.path,bytes=readFileSync(file),archive=readFileSync('art-source/v41/autochess/ui/'+path.basename(file));
 eq(bytes.subarray(0,8),Buffer.from([137,80,78,71,13,10,26,10]),label+': PNG signature');
 eq([bytes[24],bytes[25]],[8,6],label+': native RGBA8 source');
 eq([bytes.readUInt32BE(16),bytes.readUInt32BE(20)],[record.width,record.height],label+': source dimensions');
 eq(hash(bytes),record.sha256,label+': inspection is bound to exact served bytes');
 ok(bytes.equals(archive),label+': archived and public native bytes agree');
 if(existsSync(record.generatedSource))ok(bytes.equals(readFileSync(record.generatedSource)),label+': original imagegen output is untouched');
 eq(record.renderStyle,'stylized-3d',label+': official source is volumetric 3D');
 ok(record.prompt.length>100&&record.referencePaths.length>0,label+': prompt and canonical references recorded');
 for(const reference of record.referencePaths)ok(existsSync(reference),label+': generation reference is available');
 ok(record.alpha.zero>0&&record.alpha.corners.every(alpha=>alpha===0),label+': genuine native outer transparency');
 eq(record.frames.length,label==='buttons'?2:1,label+': source frame count');
 ok(record.frames.every(frame=>frame.visiblePixels>0&&frame.edgePixels===0),label+': complete isolated frames');
 const decoded=decodeNative(file);
 for(const frame of record.frames){
  const center=frame.center;let strong=0,maximum=0,alphaTotal=0,rgb=[0,0,0];
  for(let y=center.y;y<center.y+center.h;y++)for(let x=center.x;x<center.x+center.w;x++){
   const at=(y*decoded.width+x)*4,alpha=decoded.pixels[at+3];strong+=Number(alpha>=16);maximum=Math.max(maximum,alpha);alphaTotal+=alpha;
   for(let channel=0;channel<3;channel++)rgb[channel]+=decoded.pixels[at+channel];
  }
  const count=center.w*center.h;
  if(record.centerKind==='transparent')ok(strong===0&&maximum<=1&&alphaTotal/count<.03,label+': center retains native transparency without visible fill');
  else ok(alphaTotal/count>240&&rgb.every(value=>value/count<70),label+': dark clear center supports real DOM text');
 }
 if(label==='buttons')ok(record.frames[0].pixelHash!==record.frames[1].pixelHash,'button quiet and active native states are visually distinct');
}

for(const[id,entry]of Object.entries(entries)){
 const record=manifest.nativeSources.find(record=>record.path===entry.src),row=id==='buttonActive'?1:0,cell=record.frames[row].crop,crop=entry.crop;
 ok(crop.x>=cell[0]&&crop.y>=cell[1]&&crop.x+crop.w<=cell[0]+cell[2]&&crop.y+crop.h<=cell[1]+cell[3],id+': viewport stays inside its source cell');
 const [x,y,w,h]=record.frames[row].visibleBounds;
 ok(crop.x<=x&&crop.y<=y&&crop.x+crop.w>=x+w&&crop.y+crop.h>=y+h,id+': viewport retains complete native hardware');
 ok(entry.slice.every(value=>value>0)&&entry.slice[1]+entry.slice[3]<crop.w&&entry.slice[0]+entry.slice[2]<crop.h,id+': nine-slice has a positive useful center');
 eq(entry.safeArea,{x:entry.slice[3],y:entry.slice[0],w:crop.w-entry.slice[1]-entry.slice[3],h:crop.h-entry.slice[0]-entry.slice[2]},id+': measured content area');
 const svg=readFileSync('public'+entry.frameSrc,'utf8'),archive=readFileSync('art-source/v41/autochess/ui/'+path.basename(entry.frameSrc),'utf8');
 eq(svg,archive,id+': public viewport matches provenance archive');
 eq(svg.match(/<([a-z]+)\b/g),['<svg','<image'],id+': viewport draws only the native PNG image');
 eq(svg.match(/viewBox="([^"]+)"/)[1],`0 0 ${crop.w} ${crop.h}`,id+': normalized SVG origin for CSS border-image');
 ok(svg.includes(`<image x="${-crop.x}" y="${-crop.y}" width="${entry.sheetWidth}" height="${entry.sheetHeight}"`),id+': image offset selects the unchanged measured crop');
 const embedded=Buffer.from(svg.match(/href="data:image\/png;base64,([^"]+)"/)[1],'base64');
 ok(embedded.equals(readFileSync('public'+entry.src)),id+': embedded source contains exactly the original PNG bytes');
}
eq(manifest.backgrounds.map(record=>record.id).sort(),['academy-3d','academy-atmosphere'],'both 3D academy environments are registered');
eq(art.AUTO_CHESS_ATMOSPHERE_V41,'/assets/v41/autochess/ui/academy-atmosphere.png','official atmosphere path');
for(const background of manifest.backgrounds){
 const bytes=readFileSync('public'+background.path),archive='art-source/v41/autochess/'+background.path.split('/autochess/')[1],prompt=json(path.resolve('art-source/v41/autochess/ui',background.promptFile));
 ok(bytes.equals(readFileSync(archive)),background.id+': public/archive native bytes agree');
 eq(hash(bytes),background.sha256,background.id+': refreshed native background hash');
 eq([bytes.readUInt32BE(16),bytes.readUInt32BE(20)],[background.width,background.height],background.id+': registered dimensions');
 eq(prompt.tool,'image_gen',background.id+': native generation provenance');
 eq(prompt.transparent_background,false,background.id+': opaque environment requested');
 eq(background.renderStyle,'stylized-3d',background.id+': 3D official environment');
 ok(existsSync(prompt.reference),background.id+': canonical visual reference exists');
 if(existsSync(prompt.native_source))ok(bytes.equals(readFileSync(prompt.native_source)),background.id+': original environment PNG is untouched');
 if(background.id==='academy-3d'){
  eq(background.width,background.height,'arena remains square for the existing square camera');
  eq(background.camera,'orthographic-top-down','arena projection follows the existing topology');
  eq(background.targetTileBounds,{x:.125,y:.125,w:.75,h:.75},'prompt preserves existing requested arena bounds');
 }else ok(Math.abs(background.width/background.height-16/9)<.01,'atmosphere remains panoramic');
}

eq(Object.keys(idle).sort(),catalog.map(piece=>piece.id).sort(),'all 31 playable bodies have compact idle viewports');
eq(Object.keys(idle).sort(),Object.keys(pieces).sort(),'compact registry covers the final native piece registry');
eq(measurements.pieces.length,31,'all measured idle silhouettes are recorded');
eq(measurements.pixelEditingPerformed,false,'compact viewports never modify sprite pixels');
for(const measurement of measurements.pieces){
 const id=measurement.id,entry=idle[id],source=pieces[id],record=pieceRecords.get(source.src),cell=source.idle[0],crop=entry.crop;
 eq(entry.src,source.src,id+': compact body uses the original final sprite');
 eq([entry.sheetWidth,entry.sheetHeight],[source.sheetWidth,source.sheetHeight],id+': compact body source dimensions');
 eq(crop,measurement.crop,id+': measured and runtime body crops agree');
 eq(measurement.sourceCell,cell,id+': crop is based on idle frame zero');
 eq(measurement.visibleBounds,record.cells[0].visibleBounds,id+': native alpha silhouette measurement');
 eq(hash(readFileSync('public'+entry.src)),measurement.sha256,id+': compact crop uses unchanged native bytes');
 eq(measurement.sha256,record.sha256,id+': silhouette measure is bound to the inspected source');
 const [x,y,w,h]=measurement.visibleBounds;
 ok(crop.x<=x&&crop.y<=y&&crop.x+crop.w>=x+w&&crop.y+crop.h>=y+h,id+': full silhouette, horns, wings and tails remain visible');
 ok(crop.x>=cell.x&&crop.y>=cell.y&&crop.x+crop.w<=cell.x+cell.w&&crop.y+crop.h<=cell.y+cell.h,id+': no neighboring pose enters the body viewport');
 ok(crop.anchorX>=crop.x&&crop.anchorX<crop.x+crop.w&&crop.anchorY>=crop.y&&crop.anchorY<crop.y+crop.h,id+': compact viewport anchor remains contained');
 eq(measurement.margin,10,id+': measured silhouette retains up to ten native pixels of padding');
 eq(measurement.alphaVisibilityThreshold,16,id+': consistent native alpha visibility threshold');
}
console.log(`Auto Chess native art v41: PASS ${checks} checks; 5 stylized 3D UI frames, 2 native 3D environments, 31 complete compact 2D bodies`);
